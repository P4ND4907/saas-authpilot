import { writeFileSync, readFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const dataSource = readFileSync(path.join(root, "src", "data.ts"), "utf8");
const marker = "export const product = ";
const start = dataSource.indexOf(marker);
const end = dataSource.indexOf(";\n\nexport const initialRecords", start);

if (start === -1 || end === -1) {
  throw new Error("Could not find the exported product object in src/data.ts.");
}

const productLiteral = dataSource.slice(start + marker.length, end);
const product = Function(`"use strict"; return (${productLiteral});`)();
const secretKey = process.env.STRIPE_SECRET_KEY;
const siteUrl =
  process.env.PUBLIC_SITE_URL ??
  `https://${String(product.githubOwner ?? "P4ND4907").toLowerCase()}.github.io/${product.repo}/`;

if (!secretKey || !secretKey.startsWith("sk_")) {
  throw new Error("Set STRIPE_SECRET_KEY to a Stripe secret key before running this script.");
}

function form(params) {
  const body = new URLSearchParams();

  for (const [key, value] of Object.entries(params)) {
    if (value !== undefined && value !== null) {
      body.set(key, String(value));
    }
  }

  return body;
}

async function stripeRequest(pathname, params, idempotencyKey) {
  const response = await fetch(`https://api.stripe.com/v1${pathname}`, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${secretKey}`,
      "Content-Type": "application/x-www-form-urlencoded",
      "Idempotency-Key": idempotencyKey,
      "Stripe-Version": "2026-02-25.clover",
    },
    body: form(params),
  });
  const text = await response.text();
  const json = text ? JSON.parse(text) : {};

  if (!response.ok) {
    throw new Error(json.error?.message ?? text);
  }

  return json;
}

function envNameForPlan(planName) {
  if (planName === "Network") return "VITE_STRIPE_ENTERPRISE_URL";

  return `VITE_STRIPE_${planName.toUpperCase().replace(/[^A-Z0-9]+/g, "_")}_URL`;
}

const lines = [
  "# Generated by npm run stripe:links.",
  "# Do not commit this file; the built docs assets contain the public Payment Link URLs.",
];
const linkSummary = {};

for (const plan of product.pricingPlans) {
  const slug = plan.name.toLowerCase().replace(/[^a-z0-9]+/g, "-");
  const baseKey = `${product.repo}-${slug}-${plan.monthlyPrice}`;
  const stripeProduct = await stripeRequest(
    "/products",
    {
      name: `${product.name} ${plan.name}`,
      description: plan.promise,
      "metadata[app]": product.repo,
      "metadata[plan]": plan.name,
      "metadata[source]": "codex-static-saas-mvp",
    },
    `product-${baseKey}`,
  );
  const price = await stripeRequest(
    "/prices",
    {
      currency: "usd",
      unit_amount: Number(plan.monthlyPrice) * 100,
      "recurring[interval]": "month",
      product: stripeProduct.id,
      "metadata[app]": product.repo,
      "metadata[plan]": plan.name,
      "metadata[annual_price]": plan.annualPrice,
    },
    `price-${baseKey}`,
  );
  const paymentLink = await stripeRequest(
    "/payment_links",
    {
      "line_items[0][price]": price.id,
      "line_items[0][quantity]": 1,
      "after_completion[type]": "redirect",
      "after_completion[redirect][url]": `${siteUrl}?checkout=success&plan=${encodeURIComponent(plan.name)}`,
      "metadata[app]": product.repo,
      "metadata[plan]": plan.name,
    },
    `payment-link-${baseKey}`,
  );

  const envName = envNameForPlan(plan.name);
  lines.push(`${envName}=${paymentLink.url}`);
  linkSummary[plan.name] = paymentLink.url;
}

writeFileSync(path.join(root, ".env.production.local"), `${lines.join("\n")}\n`);
writeFileSync(path.join(root, "stripe-links.json"), `${JSON.stringify(linkSummary, null, 2)}\n`);

console.log(`Created Stripe Payment Links for ${product.name}.`);
console.log("Next: npm run pages:build, then commit and push docs.");
